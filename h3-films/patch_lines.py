def render(rows, indent="      "):
    lines = []
    for i, (sp, tx) in enumerate(rows):
        head = indent + "[" if i == 0 else indent + " "
        tail = "]," if i == len(rows) - 1 else ","
        lines.append('%s("%s", "%s")%s' % (head, sp, tx.replace('"', '\\"'), tail))
    return "\n".join(lines)


def patch(path, table):
    src = open(path, encoding="utf-8").read()
    # dialogue 块：以 `      [(` 开头（元组），到 `)],` 结束；beats 块以 `      ["` 开头（字符串）
    pat = re.compile(r"(?ms)^      \[\(.*?\)\],\n")
    blocks = list(pat.finditer(src))
    if len(blocks) != 20:
        print("!! %s 匹配到 %d 个 dialogue 块（期望 20）" % (os.path.basename(path), len(blocks)))
        sys.exit(1)
    out, prev = [], 0
    for idx, m in enumerate(blocks):
        no = idx + 1
        out.append(src[prev:m.start()])
        out.append(render(table[no]) + "\n")
        prev = m.end()
    out.append(src[prev:])
    open(path, "w", encoding="utf-8").write("".join(out))
    print("✓ %s：替换 %d 个 dialogue 块" % (os.path.basename(path), len(blocks)))


def verify(path_mod, jf, label):
    spec = importlib.util.spec_from_file_location(path_mod, os.path.join(ROOT, path_mod + ".py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    clean = lambda x: re.sub(r"[^\u4e00-\u9fff0-9A-Za-z]", "", x)
    j = json.load(open(os.path.join(ROOT, jf), encoding="utf-8"))
    bad = 0
    for i, s in enumerate(m.SHOTS):
        a = clean("".join(tx for _, tx in s["dialogue"]))
        b = clean(j["shots"][i]["text"])
        if a != b:
            bad += 1
            print("  镜%-3d 不一致 我的 %d 字 / 原片 %d 字" % (s["no"], len(a), len(b)))
