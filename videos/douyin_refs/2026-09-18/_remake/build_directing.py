CAMERA_BY_LEN = [
    (1.30, "几乎静态，只留极轻微的手持呼吸感；不推不摇"),
    (2.50, "极缓推近（幅度控制在画面 3% 以内）"),
    (4.00, "缓推或缓摇，幅度小、匀速，结尾停稳"),
    (99.0, "一次完整的小幅运动（推或跟随），中途不折返，末 0.5s 停稳"),
]


def camera_for(sec, rule_cam=None):
    if rule_cam:
        return rule_cam
    for lim, desc in CAMERA_BY_LEN:
        if sec <= lim:
            return desc
    return CAMERA_BY_LEN[-1][1]


def build(film, lst):
    rules = RULES.get(film, [])
    pools = POOLS.get(film, {})
    seat = {}
    out = []
    for i, r in enumerate(lst):
        seg = r["seg"]
        line = r["line"] or ""
        act = cam = None
        for pat, a, c in rules:
            if re.search(pat, line):
                act, cam = a, c
                break
        pool = pools.get(seg, [("人物保持自然微动作，环境有轻微流动", "静态微晃")])
        if act is None:
            k = seat.get(seg, 0) % len(pool)
            act, cam = pool[k]
            seat[seg] = seat.get(seg, 0) + 1
            src = "pool"
        else:
            src = "rule"
        # 连贯锚点：由 scene + 上一镜说话人 + 景别推导
        prev = lst[i - 1] if i else None
        nxt = lst[i + 1] if i + 1 < len(lst) else None
        anchor = []
        anchor.append(f"接上一镜：{prev['speaker']}说完「{(prev['line'] or '')[-8:]}」" if prev and prev.get("line") else "接上一镜同一空间")
        anchor.append(f"本镜空间：{r['scene'] or '沿用上场'}")
        if nxt and nxt.get("speaker") and nxt["speaker"] != r.get("speaker"):
            anchor.append(f"为下一镜留位：{nxt['speaker']}入画")
        out.append(dict(
            index=r["index"], start=r["start"], end=r["end"], dur=r["dur"],
            frames=r["frames"], sec=r["sec"], framing=r["framing"], kf=r["kf"],
            speaker=r["speaker"], line=line, seg=seg, func=r["func"],
            action=act, camera=camera_for(r["sec"], cam), src=src,
            anchor=" / ".join(anchor),
        ))
    return out


def main():
    rows = json.load(open(f"{HERE}/shots_all.json", encoding="utf-8"))
    allout = {}
